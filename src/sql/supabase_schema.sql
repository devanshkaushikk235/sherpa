-- ==============================================================================
-- Forecast Reliability & LiveOps Benchmark - Supabase PostgreSQL Schema
-- Run this in your Supabase SQL Editor (Dashboard -> SQL Editor -> New Query -> Run)
-- ==============================================================================

-- 1. Game Player Count Time Series
CREATE TABLE IF NOT EXISTS public.liveops_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    app_id BIGINT NOT NULL,
    date DATE NOT NULL,
    y_peak DOUBLE PRECISION,
    y_avg DOUBLE PRECISION,
    is_imputed BOOLEAN DEFAULT FALSE,
    is_outage BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(game_id, date)
);

-- 2. Game Updates & Patch Events
CREATE TABLE IF NOT EXISTS public.liveops_patches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    patch_id TEXT NOT NULL,
    date DATE NOT NULL,
    title TEXT,
    magnitude DOUBLE PRECISION,
    patch_type TEXT NOT NULL, -- 'major' or 'minor'
    overlaps_prev BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(game_id, patch_id)
);

-- 3. Post-Patch Window Strata Performance Metrics
CREATE TABLE IF NOT EXISTS public.liveops_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    model TEXT NOT NULL,
    arm TEXT NOT NULL, -- 'fixed', 'rolling', 'triggered', 'aci', 'scheduled'
    level DOUBLE PRECISION NOT NULL, -- 0.8 or 0.9
    "window" TEXT NOT NULL, -- 'baseline (>30d)', 'post_patch (0-7d)', etc.
    n BIGINT NOT NULL,
    coverage DOUBLE PRECISION NOT NULL,
    mean_width DOUBLE PRECISION NOT NULL,
    winkler DOUBLE PRECISION NOT NULL,
    mae DOUBLE PRECISION,
    smape DOUBLE PRECISION,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(game_id, model, arm, level, "window")
);

-- 4. Asymmetric Capacity Loss Simulation
CREATE TABLE IF NOT EXISTS public.liveops_capacity_sensitivity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    model TEXT NOT NULL,
    arm TEXT NOT NULL,
    level DOUBLE PRECISION NOT NULL,
    penalty_ratio DOUBLE PRECISION NOT NULL, -- 2.0, 5.0, 10.0
    norm_cost DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(game_id, model, arm, level, penalty_ratio)
);

-- 5. Prediction Intervals & Bounds
CREATE TABLE IF NOT EXISTS public.liveops_intervals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id TEXT NOT NULL,
    origin_date DATE NOT NULL,
    horizon INT NOT NULL,
    target_date DATE NOT NULL,
    model TEXT NOT NULL,
    arm TEXT NOT NULL,
    level DOUBLE PRECISION NOT NULL,
    lo DOUBLE PRECISION NOT NULL,
    hi DOUBLE PRECISION NOT NULL,
    y_true DOUBLE PRECISION,
    covered BOOLEAN NOT NULL,
    width DOUBLE PRECISION NOT NULL,
    norm_width DOUBLE PRECISION NOT NULL,
    days_since_patch DOUBLE PRECISION,
    patch_type TEXT,
    in_patch_window BOOLEAN
);

-- ==============================================================================
-- Row-Level Security (RLS) Policies
-- ==============================================================================

ALTER TABLE public.liveops_series ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.liveops_patches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.liveops_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.liveops_capacity_sensitivity ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.liveops_intervals ENABLE ROW LEVEL SECURITY;

